    private static string? _forced;
    /// <summary>Force a UI language (null/empty = follow the system UI culture).</summary>
    public static void Configure(string? forced) => _forced = string.IsNullOrEmpty(forced) ? null : forced;

    public static IEnumerable<string> Supported => S.Keys;

    public static string Language
    {
        get
        {
            if (_forced is not null && S.ContainsKey(_forced)) return _forced;
            var c = System.Globalization.CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
            return S.ContainsKey(c) ? c : "en";
        }
    }

    public static string T(string key)
    {
        var lang = Language;
        if (S.TryGetValue(lang, out var d) && d.TryGetValue(key, out var v)) return v;
        return S["en"].TryGetValue(key, out var e) ? e : key;
    }

    /// <summary>
    /// True when this language has every string English has. The WinUI rewrite added ~50 strings that
    /// only en/uk/ru have been translated into, so the rest fall back to English for those — the
    /// language picker says so instead of pretending. Completing a language makes its label change on
    /// its own; there is no separate list to keep in step.
    /// </summary>
    public static bool IsComplete(string lang) =>
        lang.Length == 0 || lang == "en" ||
        (S.TryGetValue(lang, out var d) && S["en"].Keys.All(d.ContainsKey));

    /// <summary>Localized string with positional args, filling %@/%d placeholders in order.</summary>
    public static string Tf(string key, params object[] args)
    {
        int i = 0;
        return Regex.Replace(T(key), "%@|%d", _ => i < args.Length ? (args[i++]?.ToString() ?? "") : "");
    }
